const h2 = (id: string, eb: string, t: string, toc?: string): LifeMapBlock => ({
  type: "h2",
  id,
  eb,
  t,
  toc: toc || t,
});
const h3 = (t: string, eb = ""): LifeMapBlock => ({ type: "h3", t, eb });
const p = (t: string): LifeMapBlock => ({ type: "p", t });
const ps = (arr: string[]): LifeMapBlock[] => arr.map(p);
const lead = (t: string): LifeMapBlock => ({ type: "lead", t });
const img = (id: string): LifeMapBlock => ({ type: "img", id });
const pair = (a: string, b: string): LifeMapBlock => ({ type: "pair", a, b });
const figs = (list: LifeMapFig[]): LifeMapBlock => ({ type: "figs", list });
const items = (list: LifeMapItem[]): LifeMapBlock => ({ type: "items", list });
const bullets = (list: string[]): LifeMapBlock => ({ type: "bullets", list });
const note = (label: string, title: string, t: string[], crit = ""): LifeMapBlock => ({
  type: "note",
  label,
  title,
  t,
  crit,
});
const quote = (t: string): LifeMapBlock => ({ type: "quote", t });
const mantra = (t: string): LifeMapBlock => ({ type: "mantra", t });

